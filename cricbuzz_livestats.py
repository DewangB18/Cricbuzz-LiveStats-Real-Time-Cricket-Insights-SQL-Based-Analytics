import sqlite3
import pandas as pd

DB_NAME = "cricbuzz_livestats.db"

def create_player(player_id, full_name, team_id, playing_role):
    with sqlite3.connect(DB_NAME) as conn:
        conn.execute("PRAGMA foreign_keys = ON")
        conn.execute("""
            INSERT INTO players
                (player_id, full_name, team_id, playing_role)
            VALUES (?, ?, ?, ?)
        """, (player_id, full_name, team_id, playing_role))
    print(f"Created player: {full_name}")


def read_player(player_id):
    with sqlite3.connect(DB_NAME) as conn:
        result = pd.read_sql_query("""
            SELECT p.player_id, p.full_name,
                   t.team_name, p.playing_role
            FROM players p
            LEFT JOIN teams t ON p.team_id = t.team_id
            WHERE p.player_id = ?
        """, conn, params=(player_id,))

    display(result)
    return result


def update_player_role(player_id, new_role):
    with sqlite3.connect(DB_NAME) as conn:
        cursor = conn.execute("""
            UPDATE players
            SET playing_role = ?
            WHERE player_id = ?
        """, (new_role, player_id))

    if cursor.rowcount:
        print("Player role updated.")
    else:
        print("Player not found.")


def delete_player(player_id):
    with sqlite3.connect(DB_NAME) as conn:
        cursor = conn.execute("""
            DELETE FROM players
            WHERE player_id = ?
        """, (player_id,))

    if cursor.rowcount:
        print("Player deleted.")
    else:
        print("Player not found.")

