def refresh_api_matches(api_df):
    """Insert new matches or update existing matches by match ID."""

    if api_df.empty:
        raise ValueError("No matches extracted; database not changed.")

    if api_df["api_match_id"].isna().any():
        raise ValueError("Missing match IDs; database not changed.")

    if api_df["api_match_id"].duplicated().any():
        raise ValueError("Duplicate match IDs; database not changed.")

    with sqlite3.connect(DB_PATH) as conn:
        columns = {
            row[1] for row in conn.execute(
                "PRAGMA table_info(api_matches)"
            )
        }

        if not set(DB_COLUMNS).issubset(columns):
            raise ValueError("Database schema does not match workflow.")

        placeholders = ", ".join("?" for _ in DB_COLUMNS)
        names = ", ".join(f'"{c}"' for c in DB_COLUMNS)
        updates = ", ".join(
            f'"{c}" = excluded."{c}"'
            for c in DB_COLUMNS if c != "api_match_id"
        )

        sql = f"""
            INSERT INTO api_matches ({names})
            VALUES ({placeholders})
            ON CONFLICT(api_match_id) DO UPDATE SET {updates}
        """

        rows = api_df.astype(object).where(
            pd.notna(api_df), None
        ).values.tolist()

        conn.executemany(sql, rows)

        total = conn.execute(
            "SELECT COUNT(*) FROM api_matches"
        ).fetchone()[0]

        unique_ids = conn.execute(
            "SELECT COUNT(DISTINCT api_match_id) FROM api_matches"
        ).fetchone()[0]

        integrity = conn.execute(
            "PRAGMA integrity_check"
        ).fetchone()[0]

    if total != unique_ids or integrity != "ok":
        raise RuntimeError("Database verification failed.")

    return total, unique_ids, integrity


