import requests, json, pandas as pd, gradio as gr
from datetime import datetime

BASE = 'https://api.cricwix.com/ext/v1'
LAST_MATCHES = []

def api_get(path, api_key, params=None):
    key = (api_key or '').strip()
    if not key:
        raise ValueError('Paste your Cricwix API key into the dashboard first.')
    response = requests.get(BASE + path,
        headers={'X-Api-Key': key, 'Accept': 'application/json'},
        params=params, timeout=30)
    if response.status_code == 401:
        raise ValueError('API key rejected (401). Check the key in your Cricwix account.')
    if response.status_code == 403:
        raise ValueError('Access denied (403). Check your API plan or permissions.')
    if response.status_code == 429:
        raise ValueError('API request quota reached (429). Wait or check your provider plan.')
    response.raise_for_status()
    payload = response.json()
    if isinstance(payload, dict) and payload.get('success') is False:
        raise ValueError(str(payload.get('message') or payload.get('error') or payload))
    return payload

def get_data(payload):
    return payload.get('data', payload) if isinstance(payload, dict) else payload

def team_name(team, fallback):
    if isinstance(team, dict):
        return str(team.get('team_name') or team.get('name') or team.get('short_code') or fallback)
    return str(team or fallback)

def match_id(m):
    return str(m.get('fixture_id') or m.get('match_id') or m.get('id') or '')

def match_status(m):
    return str(m.get('fixture_status') or m.get('status') or m.get('state') or 'Status unavailable')

def match_format(m):
    return str(m.get('format') or m.get('match_format') or m.get('match_type') or m.get('type') or '')

def match_score(m):
    home = m.get('home_team') or m.get('team1') or {}
    away = m.get('away_team') or m.get('team2') or {}
    def sc(t):
        if isinstance(t, dict): return str(t.get('score') or t.get('runs') or '—')
        return '—'
    return f'{sc(home)}  |  {sc(away)}'

def normalize_match(m):
    home = m.get('home_team') or m.get('team1') or {}
    away = m.get('away_team') or m.get('team2') or {}
    league = m.get('league') or m.get('series') or {}
    venue = m.get('venue') or {}
    return {
        'Match ID': match_id(m),
        'Match': team_name(home, 'Team 1') + ' vs ' + team_name(away, 'Team 2'),
        'Format': match_format(m),
        'Status': match_status(m),
        'Score': match_score(m),
        'Tournament': league.get('name','') if isinstance(league,dict) else str(league),
        'Venue': venue.get('name','') if isinstance(venue,dict) else str(venue),
        'Start time (UTC)': str(m.get('scheduled_start') or m.get('start_time') or ''),
    }

def fixture_list(payload):
    data = get_data(payload)
    if isinstance(data, list): return data
    if isinstance(data, dict):
        for key in ('fixtures','matches','results','items'):
            if isinstance(data.get(key), list): return data[key]
    return []

def load_matches(api_key, filter_name):
    global LAST_MATCHES
    status_param = {'Live now':'live', 'Upcoming':'upcoming', 'Recently completed':'finished', 'All statuses':'all'}[filter_name]
    try:
        payload = api_get('/fixtures', api_key, {'status': status_param})
        LAST_MATCHES = fixture_list(payload)
        rows = [normalize_match(m) for m in LAST_MATCHES]
        df = pd.DataFrame(rows, columns=['Match ID','Match','Format','Status','Score','Tournament','Venue','Start time (UTC)'])
        choices=[]
        for m in LAST_MATCHES:
            mid=match_id(m)
            home=m.get('home_team') or m.get('team1') or {}
            away=m.get('away_team') or m.get('team2') or {}
            label=f'{team_name(home,"Team 1")} vs {team_name(away,"Team 2")} · ID {mid}'
            if mid: choices.append((label, mid))
        selection = gr.update(choices=choices, value=choices[0][1] if choices else None)
        if not rows:
            msg='API connected successfully, but no fixtures were returned for this filter. Try All statuses or Upcoming.'
        else:
            msg=f'✅ API connected · {len(rows)} fixture(s) loaded at {datetime.now().strftime("%Y-%m-%d %H:%M:%S")} (Colab time). Click Load matches again to refresh.'
        return df, msg, selection
    except Exception as e:
        LAST_MATCHES=[]
        return pd.DataFrame(columns=['Match ID','Match','Format','Status','Score','Tournament','Venue','Start time (UTC)']), f'Could not load matches: {e}', gr.update(choices=[], value=None)

def load_detail(api_key, chosen_id, detail_type):
    if not chosen_id: return 'Choose a match first.'
    try:
        if detail_type == 'Live details':
            payload=api_get('/live/' + requests.utils.quote(str(chosen_id), safe=''), api_key)
        else:
            payload=api_get('/fixtures/' + requests.utils.quote(str(chosen_id), safe='') + '/scorecard', api_key)
        return '### ' + detail_type + '\n\n```json\n' + json.dumps(payload, indent=2, ensure_ascii=False)[:22000] + '\n```'
    except Exception as e:
        return f'### Could not load {detail_type.lower()}\n\n{e}\n\nThis match may not have scorecard/live-detail coverage on your plan. Check the provider documentation at https://cricwix.com/.'

