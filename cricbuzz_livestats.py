def refresh_api_matches(new_df):
    """Insert new matches and update existing matches by API match ID."""

    if not isinstance(new_df, pd.DataFrame):
        raise TypeError("Input must be a pandas DataFrame.")

    if new_df.empty:
        print("No API matches supplied. Database unchanged.")
        return

    if "api_match_id" not in new_df.columns:
        raise ValueError("Missing required column: api_match_id")

    if new_df["api_match_id"].isna().any():
        raise ValueError("Missing API match IDs. Database unchanged.")

    if new_df["api_match_id"].duplicated().any():
        raise ValueError("Duplicate API match IDs in input.")

    with sqlite3.connect(DB_PATH) as conn:
        existing_columns = {
            row[1]
            for row in conn.execute("PRAGMA table_info(api_matches)")
        }

        if not existing_columns:
            raise RuntimeError("api_matches table was not found.")

        if not set(new_df.columns).issubset(existing_columns):
            raise ValueError("Input contains columns absent from api_matches.")

        columns = list(new_df.columns)
        column_sql = ", ".join(f'"{col}"' for col in columns)
        placeholders = ", ".join("?" for _ in columns)

        update_columns = [
            col for col in columns if col != "api_match_id"
        ]

        update_sql = ", ".join(
            f'"{col}" = excluded."{col}"'
            for col in update_columns
        )

        sql = f"""
            INSERT INTO api_matches ({column_sql})
            VALUES ({placeholders})
            ON CONFLICT(api_match_id) DO UPDATE SET
            {update_sql}
        """

        conn.executemany(
            sql,
            new_df.astype(object).where(
                pd.notna(new_df), None
            ).values.tolist()
        )

        total = conn.execute(
            "SELECT COUNT(*) FROM api_matches"
        ).fetchone()[0]

        unique_ids = conn.execute(
            "SELECT COUNT(DISTINCT api_match_id) FROM api_matches"
        ).fetchone()[0]

        integrity = conn.execute(
            "PRAGMA integrity_check"
        ).fetchone()[0]

    print("API refresh completed.")
    print("Rows processed:", len(new_df))
    print("Total API matches in database:", total)
    print("Unique API match IDs:", unique_ids)
    print("Database integrity:", integrity)

